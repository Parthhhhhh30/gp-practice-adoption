import {test,expect,devices} from '@playwright/test';
const url=process.env.TEST_URL||'https://casework-investigation-desk-parthhhh.vercel.app/';
test('real API-backed GraphQL diagnosis and closure gate',async({page})=>{
  const requests=[];page.on('response',r=>{if(r.url().includes('/api/graphql'))requests.push({status:r.status(),url:r.url()})});
  await page.goto(url+'?desk=1');await expect(page.locator('#case-title')).toContainText('save that never saved');
  await page.getByRole('button',{name:'Activity record'}).click();
  await page.getByRole('button',{name:'Attempt verified closure'}).click();
  await expect(page.locator('#tab-panel')).toContainText('A passing diagnostic');
  await page.getByRole('button',{name:'Investigate'}).click();
  await page.getByRole('button',{name:/Run diagnostic/}).click();
  await expect(page.locator('#tab-panel')).toContainText('GRAPHQL_VALIDATION_ERROR');
  await page.getByRole('button',{name:/Correct missing variable/}).click();
  await page.getByRole('button',{name:/Run diagnostic/}).click();
  await expect(page.locator('#tab-panel')).toContainText('MUTATION_OK');
  expect(requests).toHaveLength(2);expect(requests.every(x=>x.status===200)).toBeTruthy();
  await page.getByRole('button',{name:/Record verified outcome/}).click();
  await page.locator('#note').fill('GraphQL returned HTTP 200 but an application-level missing-draftId error. Corrected and verified with a retest.');
  await page.getByRole('button',{name:'Save evidence notes'}).click();
  await page.getByRole('button',{name:'Customer response'}).click();
  await page.getByRole('button',{name:/Check and approve draft/}).click();
  await page.getByRole('button',{name:'Activity record'}).click();
  await expect(page.locator('#tab-panel')).toContainText('Closure gate: READY');
  await page.getByRole('button',{name:'Attempt verified closure'}).click();
  await expect(page.locator('#case-status')).toContainText('Resolved');
  await page.reload();await expect(page.locator('#case-status')).toContainText('Resolved');
});
test('security escalation is urgent and not blocked by missing routine notes',async({page})=>{
  await page.goto(url+'?desk=1');await page.locator('[data-case="CW-307"]').click();
  await page.getByRole('button',{name:/Simulate possible data exposure/}).click();
  await page.getByRole('button',{name:'Escalation'}).click();
  await expect(page.locator('#target')).toHaveValue('Security');
  await page.locator('#reason').fill('Potential unintended access to confidential fictional documents requires urgent Security review.');
  await page.getByRole('button',{name:'Validate and record handover'}).click();
  await expect(page.locator('#case-status')).toHaveText('Escalated');
  await expect(page.locator('#tab-panel')).toContainText('Urgent security review');
  await page.getByRole('button',{name:'Activity record'}).click();
  await page.getByRole('button',{name:'Attempt verified closure'}).click();
  await expect(page.locator('#tab-panel')).toContainText('Possible confidentiality incident');
});
